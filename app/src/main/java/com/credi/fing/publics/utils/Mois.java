package com.credi.fing.publics.utils;
import java.util.ArrayList;

public class Mois {
    private String mois;
    private ArrayList<String> jours;

    public Mois() {
    }

    public String getMois() {
        return mois;
    }

    public void setMois(String mois) {
        this.mois = mois;
    }

    public ArrayList<String> getJours() {
        return jours;
    }

    public void setJours(ArrayList<String> jours) {
        this.jours = jours;
    }
}
